<section class="missao">

<h2>Nossa Missão</h2>

<p>
Nossa empresa tem como finalidade a democratização da educação, tendo sobre vista do escopo limítrofe do ensino brasileiro – reservado a alta cúpula da cidadania brasileira – remota do período colonial, com teus alicerces vigentes até os tempos contemporâneos. O projeto tem sua gênese com estes fatos em mente, logo nossa organização almeja mitigar a desigualdade educacional, mesmo que de modo macro; por intermédio da criação de um site educacional voltado exclusivamente para os objetos de estudo da história, com o ponto fulcral em vestibulares e concursos públicos. Reconhecendo ser a educação a maior arma do oprimido, logo trabalhamos por uma partilha mais igualitária do sensível, com foco ortodoxo em pessoas menos abastadas socialmente, neste prisma nossa missão é em geral oferecer educação acessível e democrática para os que dela foram cerceados por séculos. Além de ofertar por meio do estudo da história, não apenas uma vil aprovação, sobretudo oferecer a quem utiliza a compreensão de seu passado, para que se explique o presente e revolucione no futuro.
</p>

</section>

<section class="missao">

<h2>Visão</h2>

<p>
Nossa visão para experiencias futuras é reta e clara:
Crescer enquanto projeto educacional, ser referencia em um estudo crítico da realidade – distante da visão positivista e industrial; tornando o conhecimento não apenas panfletário ou como meio para um fim! Em senda oposta, trabalharemos para que a obtenção do saber seja guisa da existência e não apenas um meio para aprovações. Visamos uma educação social, transformadora, igualitária e sobretudo crítica e revolucionaria.
</p>

</section>

<section class="valores">

<h2>Nossos Valores</h2>

<div class="cards">

<div class="card">
<h3>Equidade</h3>
<p>Ora, é evidente que prezamos pela equidade – em tornar a educação algo rotineiro e cotidiano ao brasileiro, não apenas um prato que está presente na mesa da burguesia.</p>
</div>

<div class="card">
<h3>Emancipação</h3>
<p>Emancipação eis a palavra! A educação em sua finalidade mais nobre deve servir a tal palavra – devemos buscar conhecimento como usufruto da alma e não porquê uma folha irá o defrontar com questões. A educação deve libertar mente, corpo e alma; e não criar o ciclo vicioso da educação industrial e mecanizada – criando seres humanos dóceis, disciplinados e acríticos.</p>
</div>

<div class="card">
<h3>Método Crítico</h3>
<p>Beberemos é claro do método crítico, justamente para acabar com a reprodução da educação espetacular e mecânica, formando assim seres pensantes e não máquinas prontas a servir o capital.</p>
</div>

<div class="card">
<h3>Social</h3>
<p>É indubitável que a educação não se desfaz do social – não se educa a burguesia ao mesmo passo da educação proletária. Tendo isto posto, nós não praticaremos a negligencia de não demonstrar ao estudante o papel fundamental do social em sua formação enquanto individuo social e estudante.</p>
</div>

<div class="card">
<h3>Democrático</h3>
<p>A democratização do ensino é nossa maior bandeira, portanto valorizamos o processo democrático da obtenção do conhecimento – pois não há real democracia sem o acesso universal a educação.</p>
</div>

<div class="card">
<h3>Diversidade</h3>
<p>Valorizamos a diversidade em todos os campos: social, religioso, étnico, racial e etc. Compreendendo que unidos nada temos a perder, muito já nos foi saqueado – não há motivos para uma luta interna.</p>
</div>

</div>

